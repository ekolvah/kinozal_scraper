"""Единственный дом denylist'а «модель не запинена» — для обоих гардов (#374, #392).

Политика одна (`docs/architecture/ci.md` §Model pinning), поверхностей две: CLI-флаг
`--model` внутри `claude_args` в `.github/workflows/agent-review.yml` и frontmatter
сабагента в `.claude/agents/*.md`.

**Почему одно множество, а не два.** Это **denylist**, а не allowlist: объединение
строго консервативнее — оно может только отвергнуть лишнее, но не пропустить.
Значение, невозможное на одной поверхности, ничего не стоит запретить и там. Раньше
наборы жили копиями в двух файлах и **уже разошлись**: `fable` был во
frontmatter-наборе и отсутствовал в CLI-наборе, из-за чего `--model fable` проходил
cloud-гард, хотя дока экшена говорит, что флаг принимает те же значения.
"""

from __future__ import annotations

# Всё, что резолвит НЕ репозиторий: алиасы уезжают на новое поколение вместе с
# апстримом, плавающие указатели — вместе с его дефолтом, `inherit` — вместе с
# моделью сессии. Любое из них означает, что качество гейта меняется без строчки
# в диффе (§IV: смена неотличима от её отсутствия).
UNPINNED_MODEL_VALUES = frozenset(
    {
        "opus",
        "sonnet",
        "haiku",
        "fable",
        "default",
        "latest",
        "inherit",
    }
)
